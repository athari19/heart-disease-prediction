import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
import warnings
warnings.filterwarnings('ignore')

from sklearn.model_selection import train_test_split, cross_val_score, StratifiedKFold
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import (accuracy_score, precision_score, recall_score,
                             f1_score, confusion_matrix, classification_report,
                             roc_curve, auc)

"""# **STEP 1: Dataset Understanding**

---


"""

df = pd.read_csv('heart.csv')

print(f"Dataset shape: {df.shape[0]} rows × {df.shape[1]} columns")
print("\nFirst 5 rows:")
print(df.head().to_string())
print("\nFeature descriptions:")
feature_desc = {
    'Age': 'Age of the patient (years)',
    'Sex': 'Gender (1=Male, 0=Female)',
    'ChestPainType': 'Chest pain type (0-3)',
    'RestingBP': 'Resting blood pressure (mm Hg)',
    'Cholesterol': 'Serum cholesterol (mg/dL)',
    'FastingBS': 'Fasting blood sugar > 120 mg/dL (1=True)',
    'RestingECG': 'Resting ECG results (0-2)',
    'MaxHR': 'Maximum heart rate achieved',
    'ExerciseAngina': 'Exercise-induced angina (1=Yes)',
    'Oldpeak': 'ST depression induced by exercise',
    'ST_Slope': 'Slope of peak exercise ST segment (0-2)',
    'HeartDisease': 'Target: heart disease present (1=Yes, 0=No)'
}

for col, desc in feature_desc.items():
    print(f"  {col:<18}: {desc}")

"""# **STEP 2: EDA**"""

print("\nMissing values:")
print(df.isnull().sum())
print(f"Duplicate rows: {df.duplicated().sum()}")
print("\nTarget distribution:")
print(df['HeartDisease'].value_counts())
print("\nBasic statistics:")
print(df.describe().round(2).to_string())

"""# STEP 3: VISUALIZATIONS

**Figure 1: Target Distribution**
"""

sns.set_theme(style="whitegrid")
colors = ['#5B9BD5', '#ED7D31']

# Figure 1: Target Distribution
fig, axes = plt.subplots(1, 2, figsize=(12, 5))
fig.suptitle('Figure 1: Heart Disease Class Distribution', fontsize=14, fontweight='bold')

counts = df['HeartDisease'].value_counts().sort_index()
labels = ['No Disease', 'Heart Disease']

axes[0].bar(labels, counts.values, color=colors, edgecolor='white', width=0.5)
axes[0].set_title('Count of Cases')
axes[0].set_ylabel('Count')
for i, v in enumerate(counts.values):
    axes[0].text(i, v + 2, str(v), ha='center', fontweight='bold')

axes[1].pie(counts.values, labels=labels, autopct='%1.1f%%',
            colors=colors, startangle=90, wedgeprops={'edgecolor': 'white', 'linewidth': 2})
axes[1].set_title('Class Proportion')

plt.tight_layout()
plt.savefig('fig1_target_distribution.png', dpi=150, bbox_inches='tight')
print("Saved: fig1_target_distribution.png")

"""**Figure 2: Numeric Distributions**


"""

# Figure 2: Numeric Distributions
fig, axes = plt.subplots(1, 3, figsize=(16, 5))
fig.suptitle('Figure 2: Key Numeric Features by Heart Disease', fontsize=14, fontweight='bold')

for i, (col, label) in enumerate(zip(['Age', 'Cholesterol', 'MaxHR'],
                                      ['Age (years)', 'Cholesterol (mg/dL)', 'Max Heart Rate'])):
    for val, color, lbl in zip([0, 1], colors, ['No Disease', 'Heart Disease']):
        axes[i].hist(df[df['HeartDisease'] == val][col], bins=20,
                     alpha=0.6, color=color, label=lbl, edgecolor='white')
    axes[i].set_title(col)
    axes[i].set_xlabel(label)
    axes[i].set_ylabel('Frequency')
    axes[i].legend(fontsize=8)

plt.tight_layout()
plt.savefig('fig2_numeric_distributions.png', dpi=150, bbox_inches='tight')
print("Saved: fig2_numeric_distributions.png")

"""**Figure 3: Categorical Features**"""

cat_cols = ['Sex', 'ChestPainType', 'ExerciseAngina', 'ST_Slope']
fig, axes = plt.subplots(1, len(cat_cols), figsize=(20, 5))
fig.suptitle('Figure 3: Categorical Features vs Heart Disease', fontsize=14, fontweight='bold')

for ax, col in zip(axes, cat_cols):
    ct = pd.crosstab(df[col], df['HeartDisease'])
    ct.plot(kind='bar', ax=ax, color=colors, edgecolor='white', rot=0)
    ax.set_title(col)
    ax.set_ylabel('Count')
    ax.legend(['No Disease', 'Heart Disease'], fontsize=7)

plt.tight_layout()
plt.savefig('fig3_categorical_features.png', dpi=150, bbox_inches='tight')
print("Saved: fig3_categorical_features.png")

"""**Figure 4: Correlation Heatmap**"""

fig, ax = plt.subplots(figsize=(11, 8))

# Identify categorical columns (object dtype)
categorical_cols = df.select_dtypes(include='object').columns

# Apply one-hot encoding to convert categorical columns to numerical
df_encoded = pd.get_dummies(df, columns=categorical_cols, drop_first=True) # drop_first to avoid multicollinearity

# Calculate correlation on the encoded DataFrame
corr = df_encoded.corr()

mask = np.triu(np.ones_like(corr, dtype=bool))
sns.heatmap(corr, mask=mask, annot=True, fmt='.2f', cmap='coolwarm',
            center=0, square=True, linewidths=0.5, ax=ax, cbar_kws={"shrink": 0.8})
ax.set_title('Figure 4: Feature Correlation Heatmap', fontsize=14, fontweight='bold')
plt.tight_layout()
plt.savefig('fig4_correlation_heatmap.png', dpi=150, bbox_inches='tight')
print("Saved: fig4_correlation_heatmap.png")

"""# STEP 4: PREPROCESSING

"""

df_clean = df.drop_duplicates().copy()
print(f"Rows after removing duplicates: {len(df_clean)}")

X = df_clean.drop('HeartDisease', axis=1)
y = df_clean['HeartDisease']

# Identify categorical columns and apply one-hot encoding
categorical_cols = X.select_dtypes(include='object').columns
X_encoded = pd.get_dummies(X, columns=categorical_cols, drop_first=True)

X_train, X_test, y_train, y_test = train_test_split(
    X_encoded, y, test_size=0.2, random_state=42, stratify=y
)
print(f"Train: {X_train.shape[0]} | Test: {X_test.shape[0]}")

scaler = StandardScaler()
X_train_sc = scaler.fit_transform(X_train)
X_test_sc  = scaler.transform(X_test)
print("StandardScaler applied.")

"""# STEP 5: MODEL TRAINING

"""

cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)

# Model 1: Logistic Regression
lr = LogisticRegression(max_iter=1000, random_state=42)
lr.fit(X_train_sc, y_train)
lr_pred = lr.predict(X_test_sc)
lr_cv = cross_val_score(lr, X_train_sc, y_train, cv=cv, scoring='f1').mean()
print(f"Logistic Regression — 5-Fold CV F1: {lr_cv:.4f}")

# Model 2: Random Forest
rf = RandomForestClassifier(n_estimators=100, random_state=42)
rf.fit(X_train, y_train)
rf_pred = rf.predict(X_test)
rf_cv = cross_val_score(rf, X_train, y_train, cv=cv, scoring='f1').mean()
print(f"Random Forest       — 5-Fold CV F1: {rf_cv:.4f}")

"""# STEP 6: EVALUATION

"""

def evaluate(name, y_true, y_pred):
    return {
        'Model':     name,
        'Accuracy':  round(accuracy_score(y_true, y_pred),  4),
        'Precision': round(precision_score(y_true, y_pred), 4),
        'Recall':    round(recall_score(y_true, y_pred),    4),
        'F1-Score':  round(f1_score(y_true, y_pred),        4),
    }

results = pd.DataFrame([
    evaluate('Logistic Regression', y_test, lr_pred),
    evaluate('Random Forest',       y_test, rf_pred),
])
print("\nModel Comparison:")
print(results.to_string(index=False))

print("\nLogistic Regression — Classification Report:")
print(classification_report(y_test, lr_pred, target_names=['No Disease', 'Heart Disease']))

print("Random Forest — Classification Report:")
print(classification_report(y_test, rf_pred, target_names=['No Disease', 'Heart Disease']))

# ROC AUC
lr_prob = lr.predict_proba(X_test_sc)[:, 1]
rf_prob = rf.predict_proba(X_test)[:, 1]
lr_fpr, lr_tpr, _ = roc_curve(y_test, lr_prob)
rf_fpr, rf_tpr, _ = roc_curve(y_test, rf_prob)
lr_auc = auc(lr_fpr, lr_tpr)
rf_auc = auc(rf_fpr, rf_tpr)
print(f"\nAUC — Logistic Regression: {lr_auc:.4f} | Random Forest: {rf_auc:.4f}")
print(f"CV F1 — Logistic Regression: {lr_cv:.4f} | Random Forest: {rf_cv:.4f}")

"""# STEP 7: RESULT FIGURES"""

# Figure 5: Confusion Matrices
fig, axes = plt.subplots(1, 2, figsize=(14, 5))
fig.suptitle('Figure 5: Confusion Matrices', fontsize=14, fontweight='bold')

for ax, y_pred, title in zip(axes, [lr_pred, rf_pred],
                              ['Logistic Regression', 'Random Forest']):
    cm = confusion_matrix(y_test, y_pred)
    sns.heatmap(cm, annot=True, fmt='d', cmap='Blues', ax=ax,
                xticklabels=['No Disease', 'Heart Disease'],
                yticklabels=['No Disease', 'Heart Disease'],
                linewidths=1, linecolor='white', cbar=False)
    ax.set_title(title)
    ax.set_xlabel('Predicted')
    ax.set_ylabel('Actual')

plt.tight_layout()
plt.savefig('fig5_confusion_matrices.png', dpi=150, bbox_inches='tight')
print("Saved: fig5_confusion_matrices.png")

# Figure 6: Metrics Comparison
metrics = ['Accuracy', 'Precision', 'Recall', 'F1-Score']
x = np.arange(len(metrics))
width = 0.35

fig, ax = plt.subplots(figsize=(11, 6))
lr_vals = [results.loc[0, m] for m in metrics]
rf_vals = [results.loc[1, m] for m in metrics]

b1 = ax.bar(x - width/2, lr_vals, width, label='Logistic Regression', color='#5B9BD5', edgecolor='white')
b2 = ax.bar(x + width/2, rf_vals, width, label='Random Forest',       color='#ED7D31', edgecolor='white')
ax.set_ylim(0, 1.15)
ax.set_xticks(x); ax.set_xticklabels(metrics)
ax.set_ylabel('Score')
ax.set_title('Figure 6: Model Performance Comparison', fontsize=14, fontweight='bold')
ax.legend()
ax.axhline(0.8, color='gray', linestyle='--', alpha=0.4)
for bar in list(b1) + list(b2):
    ax.text(bar.get_x() + bar.get_width()/2, bar.get_height() + 0.01,
            f'{bar.get_height():.3f}', ha='center', fontsize=9)
plt.tight_layout()
plt.savefig('fig6_model_comparison.png', dpi=150, bbox_inches='tight')
print("Saved: fig6_model_comparison.png")

# Figure 7: ROC Curves
fig, ax = plt.subplots(figsize=(8, 6))
ax.plot(lr_fpr, lr_tpr, color='#5B9BD5', lw=2, label=f'Logistic Regression (AUC={lr_auc:.3f})')
ax.plot(rf_fpr, rf_tpr, color='#ED7D31', lw=2, label=f'Random Forest (AUC={rf_auc:.3f})')
ax.plot([0, 1], [0, 1], 'k--', lw=1, label='Random Classifier')
ax.fill_between(lr_fpr, lr_tpr, alpha=0.07, color='#5B9BD5')
ax.fill_between(rf_fpr, rf_tpr, alpha=0.07, color='#ED7D31')
ax.set_xlabel('False Positive Rate')
ax.set_ylabel('True Positive Rate')
ax.set_title('Figure 7: ROC Curves Comparison', fontsize=14, fontweight='bold')
ax.legend(loc='lower right')
plt.tight_layout()
plt.savefig('fig7_roc_curves.png', dpi=150, bbox_inches='tight')
print("Saved: fig7_roc_curves.png")

# Figure 8: Feature Importance
importances = pd.Series(rf.feature_importances_, index=X_encoded.columns).sort_values(ascending=True)
fig, ax = plt.subplots(figsize=(9, 7))
importances.plot(kind='barh', ax=ax, color='#5B9BD5', edgecolor='white')
ax.set_title('Figure 8: Feature Importance (Random Forest)', fontsize=14, fontweight='bold')
ax.set_xlabel('Importance Score')
plt.tight_layout()
plt.savefig('fig8_feature_importance.png', dpi=150, bbox_inches='tight')
plt.show()
print("Saved: fig8_feature_importance.png")

